#!/usr/bin/env python3
"""Export the 12 synthetic spike-v2 cases into cases/CNN-<label>.hl7 + cases/expected.json + cases/MANIFEST,
lookup seeds into data/labcodemap.csv, and copy history/baseline JSON into data/.
Source folder is read-only. MSH-10 rewrite rule: CNN_MSGnnn -> CNN-MSGnnn (first '_' becomes '-').
All data is SYNTHETIC (generated by spike-v2-message-path/generate.py, seed 20261026). Not real patients."""
import csv, hashlib, json, os, re, shutil, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.environ.get("SPIKE_DIR", os.path.join(os.path.dirname(ROOT), "spike-v2-message-path"))
PREREG = {  # from spike-v2-message-path/prereg.md, section 3
    "data/ground_truth.json": "6baeb5386668be469b7412347f4136ddd504ba23ed29fd0ba5fb219d4585af70",
    "data/history_200.json": "1a7b74b49a5f3627a0d951a187703c7b962adbb41e0467b4faba17f188b82762",
    "data/lookup_table.json": "20674326c34e99dda90f8f5d4cc0edcc9f61d754c8ff31f316920c61cfeb3783",
    "data/baseline_dtl.json": "7669fd1dbaecbf83d27185ccd7cbe1439c3f84d6ba33762ddc00aecf87a7e3bc",
}
LABELS = {
    "C01": "new-code-sod", "C02": "pct-replaces-hct", "C03": "creat-mgdl", "C04": "glu-mgdl",
    "C05": "bun-unit-case", "C06": "duplicate-flood", "C07": "correction-resend", "C08": "prompt-injection-nte",
    "C09": "unknown-code-q77", "C10": "mrn-pid2", "C11": "critical-k", "C12": "new-code-hb",
}
MSH10_RE = re.compile(r"^(C\d\d)_(MSG\d+)$")

def sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()

def fix_id(v):
    m = MSH10_RE.match(v)
    return f"{m.group(1)}-{m.group(2)}" if m else v

def rewrite_msh10(raw):
    segs = raw.split("\r")
    f = segs[0].split("|")
    f[9] = fix_id(f[9])
    segs[0] = "|".join(f)
    return "\r".join(segs)

def main():
    ok = True
    report = []
    for rel, exp in PREREG.items():
        got = sha(os.path.join(SRC, rel))
        report.append((rel, got == exp, got))
        ok &= got == exp
    os.makedirs(os.path.join(ROOT, "cases"), exist_ok=True)
    os.makedirs(os.path.join(ROOT, "data"), exist_ok=True)
    manifest = ["# sha256  file  (source json sha256)  messages"]
    for cid, label in LABELS.items():
        src = os.path.join(SRC, "data", "cases", f"{cid}.json")
        d = json.load(open(src))
        assert d["case_id"] == cid
        out_lines = []
        for m in d["messages"]:
            raw = m["raw_hl7"].rstrip("\r")
            assert raw.split("\r")[0].split("|")[9] == m["msg_id"], m["msg_id"]
            out_lines.append(rewrite_msh10(raw) + "\r")
        name = f"{cid}-{label}.hl7"
        path = os.path.join(ROOT, "cases", name)
        with open(path, "w", newline="") as fh:
            fh.write("".join(out_lines))
        manifest.append(f"{sha(path)}  {name}  (src {sha(src)})  {len(out_lines)}")
    with open(os.path.join(ROOT, "cases", "MANIFEST"), "w") as fh:
        fh.write("\n".join(manifest) + "\n")
    gt = json.load(open(os.path.join(SRC, "data", "ground_truth.json")))
    exp = {"synthetic": True, "note": "SYNTHETIC. Derived from spike-v2 ground_truth.json; MSH-10 rewritten CNN_MSGnnn -> CNN-MSGnnn.",
           "criteria": {"multiplier_rel_tol": 0.0025,
                        "correct": "final action == action; patch_mapping: code and loinc equal; convert_unit: code equal and multiplier within 0.25%; quarantine: msh10 equal; C10 escalate only if evidence contains 'PID-2' and matches evidence_regex"},
           "cases": {}}
    for cid, label in LABELS.items():
        c = json.loads(json.dumps(gt["cases"][cid]))
        if c.get("target") and "msh10" in c["target"]:
            c["target"]["msh10"] = fix_id(c["target"]["msh10"])
        if cid == "C10":
            c["evidence_must_contain"] = "PID-2"
            c["evidence_regex"] = r"30\s*/\s*30|100\s*%|all 30"
        c["file"] = f"{cid}-{label}.hl7"
        exp["cases"][cid] = c
    json.dump(exp, open(os.path.join(ROOT, "cases", "expected.json"), "w"), indent=2)
    lt = json.load(open(os.path.join(SRC, "data", "lookup_table.json")))
    assert "SOD" not in lt and "HB" not in lt
    cols = ["canonical_code", "canonical_name", "short_name", "expected_unit", "ref_range", "panel"]
    with open(os.path.join(ROOT, "data", "labcodemap.csv"), "w", newline="") as fh:
        fh.write("# SYNTHETIC seeds from spike-v2 lookup_table.json. Lookup value = canonical_code (LOINC). SOD/HB intentionally absent (cases C01/C12).\n")
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(["local_code"] + cols)
        for k, v in lt.items():
            w.writerow([k] + [v.get(c, "") for c in cols])
    for f in ["history_200.json", "baseline_dtl.json"]:
        shutil.copyfile(os.path.join(SRC, "data", f), os.path.join(ROOT, "data", f))
    for rel, good, got in report:
        print(f"{'OK  ' if good else 'FAIL'} {rel} {got}")
    print("PREREG_SHA256=" + ("OK" if ok else "FAIL"))
    return 0 if ok else 1

if __name__ == "__main__":
    sys.exit(main())
